// segment_tables.rs

// segmentArrays are the ragel tables of segment_words.go with the Rust element type of each.
var segmentArrays = []struct{ goName, rustType string }{
	{"_s_key_offsets", "u16"},
	{"_s_trans_keys", "u8"},
	{"_s_single_lengths", "u8"},
	{"_s_range_lengths", "u8"},
	{"_s_index_offsets", "u16"},
	{"_s_indicies", "i16"},
	{"_s_trans_targs", "i16"},
	{"_s_trans_actions", "u8"},
	{"_s_to_state_actions", "u8"},
	{"_s_from_state_actions", "u8"},
	{"_s_eof_actions", "u8"},
	{"_s_eof_trans", "u16"},
}

func segmentTables(path string) string {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, path, nil, 0)
	check(err)
	vars := map[string]*ast.CompositeLit{}
	consts := map[string]int64{}
	for _, d := range f.Decls {
		g, ok := d.(*ast.GenDecl)
		if !ok {
			continue
		}
		for _, sp := range g.Specs {
			s, ok := sp.(*ast.ValueSpec)
			if !ok {
				continue
			}
			for i, n := range s.Names {
				if i >= len(s.Values) {
					continue
				}
				switch v := s.Values[i].(type) {
				case *ast.CompositeLit:
					vars[n.Name] = v
				case *ast.BasicLit:
					if g.Tok == token.CONST && v.Kind == token.INT {
						x, err := strconv.ParseInt(v.Value, 0, 64)
						check(err)
						consts[n.Name] = x
					}
				case *ast.UnaryExpr:
					if lit, ok := v.X.(*ast.BasicLit); ok && g.Tok == token.CONST && v.Op == token.SUB {
						x, err := strconv.ParseInt(lit.Value, 0, 64)
						check(err)
						consts[n.Name] = -x
					}
				}
			}
		}
	}

	var b strings.Builder
	b.WriteString(header("Copyright (c) 2015 Couchbase, Inc.", "Apache-2.0",
		"github.com/blevesearch/segment "+segmentVersion+", segment_words.go: the ragel -T1 tables of the "+
			"word segmenter,\n * generated by ragel from segment_words.rl and Unicode 8.0.0's WordBreakProperty.txt"))
	for _, c := range []string{"s_start", "s_first_final"} {
		v, ok := consts[c]
		if !ok {
			check(fmt.Errorf("constant %s not found", c))
		}
		fmt.Fprintf(&b, "/// Go's `%s`.\npub(crate) const %s: usize = %d;\n\n", c, strings.ToUpper(c), v)
	}
	for _, a := range segmentArrays {
		lit, ok := vars[a.goName]
		if !ok {
			check(fmt.Errorf("array %s not found", a.goName))
		}
		vals := make([]int64, len(lit.Elts))
		for i, e := range lit.Elts {
			vals[i] = evalInt(e)
		}
		name := strings.ToUpper(strings.TrimPrefix(a.goName, "_"))
		fmt.Fprintf(&b, "/// Go's `%s`.\npub(crate) static %s: [%s; %d] = [", a.goName, name, a.rustType, len(vals))
		for i, v := range vals {
			if i%24 == 0 {
				b.WriteString("\n    ")
			} else {
				b.WriteString(" ")
			}
			fmt.Fprintf(&b, "%d,", v)
		}
		b.WriteString("\n];\n\n")
	}
	return strings.TrimSuffix(b.String(), "\n")
}

func evalInt(e ast.Expr) int64 {
	switch x := e.(type) {
	case *ast.BasicLit:
		v, err := strconv.ParseInt(x.Value, 0, 64)
		check(err)
		return v
	case *ast.UnaryExpr:
		if x.Op == token.SUB {
			return -evalInt(x.X)
		}
	}
	check(fmt.Errorf("cannot evaluate %T", e))
	return 0
}

