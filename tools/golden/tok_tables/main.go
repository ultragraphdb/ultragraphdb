// Command tok_tables writes the Rust tables of ultragraphdb_core_tok from the Go code Dgraph's tok package runs:
//
//   - segment_tables.rs: the word-segmentation state machine of github.com/blevesearch/segment v0.9.1
//     (segment_words.go, the table-driven ragel output built from Unicode 8.0.0's WordBreakProperty.txt, which
//     bleve's unicode tokenizer runs), read as Go source;
//   - unicode_tables.rs: unicode.ToLower's mapping and the unicode.Letter ranges of the Go toolchain building this
//     command, which must be the one building Dgraph (go 1.27);
//   - stop_word_tables.rs: the stop-word token maps of bleve v2.5.7 for the 28 languages of Dgraph's
//     tok/stopwords.go, read through bleve's registry as Dgraph reads them.
//
// The segment tables are unexported, so they are read from the module's source with go/parser; nothing is copied by
// hand.
//
// Usage, from tools/golden: go run ./tok_tables
package main

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"sort"
	"strconv"
	"strings"
	"unicode"

	"github.com/blevesearch/bleve/v2/registry"

	_ "github.com/dgraph-io/dgraph/v25/tok" // registers every stop-word map Dgraph uses
)

const segmentVersion = "v0.9.1"

// stopLanguages are the keys of Dgraph's langStops (tok/stopwords.go); the token map of each is "stop_" + key.
var stopLanguages = []string{
	"ar", "bg", "ca", "ckb", "cs", "da", "de", "el", "en", "es", "eu", "fa", "fi", "fr", "ga", "gl", "hi", "hu",
	"hy", "id", "it", "nl", "no", "pt", "ro", "ru", "sv", "tr",
}

func main() {
	out, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}}", "github.com/blevesearch/segment").Output()
	check(err)
	segDir := strings.TrimSpace(string(out))
	if !strings.HasSuffix(segDir, "@"+segmentVersion) {
		check(fmt.Errorf("github.com/blevesearch/segment resolves to %s, want %s", segDir, segmentVersion))
	}
	root, err := filepath.Abs("../..")
	check(err)
	dst := filepath.Join(root, "ultragraphdb_core_tok", "src", "tables")
	check(os.MkdirAll(dst, 0o755))

	write(dst, "segment_tables.rs", segmentTables(filepath.Join(segDir, "segment_words.go")))
	write(dst, "unicode_tables.rs", unicodeTables())
	write(dst, "stop_word_tables.rs", stopWordTables())
}

func check(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, "tok_tables:", err)
		os.Exit(1)
	}
}

func write(dir, name, body string) {
	path := filepath.Join(dir, name)
	check(os.WriteFile(path, []byte(body), 0o644))
	fmt.Printf("wrote %s (%d bytes)\n", path, len(body))
}

func header(copyright, license, source string) string {
	return fmt.Sprintf(`/*
 * %s
 * SPDX-License-Identifier: %s
 *
 * Ported from %s.
 * Changed for ultragraphdb: translated to Rust.
 * Copyright (c) 2026. Marvin Hansen.
 */

// Code generated by tools/golden/tok_tables (go run ./tok_tables in tools/golden). DO NOT EDIT.

`, copyright, license, source)
}

