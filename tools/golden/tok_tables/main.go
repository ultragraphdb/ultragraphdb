func unicodeTables() string {
	var b strings.Builder
	b.WriteString(header("Copyright 2009 The Go Authors. All rights reserved.", "BSD-3-Clause",
		"the Go standard library "+runtime.Version()+", unicode (Unicode "+unicode.Version+"): ToLower and Letter"))
	fmt.Fprintf(&b, "/// The Unicode version of the Go toolchain's unicode package.\npub(crate) static GO_UNICODE_VERSION: &str = %q;\n\n", unicode.Version)

	var pairs [][2]rune
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if l := unicode.ToLower(r); l != r {
			pairs = append(pairs, [2]rune{r, l})
		}
	}
	fmt.Fprintf(&b, "/// Every rune `unicode.ToLower` changes, as `(rune, lower)`, sorted.\npub(crate) static TO_LOWER: [(u32, u32); %d] = [", len(pairs))
	for i, p := range pairs {
		if i%8 == 0 {
			b.WriteString("\n    ")
		} else {
			b.WriteString(" ")
		}
		fmt.Fprintf(&b, "(0x%x, 0x%x),", p[0], p[1])
	}
	b.WriteString("\n];\n\n")

	var ranges [][2]rune
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if !unicode.IsLetter(r) {
			continue
		}
		if n := len(ranges); n > 0 && ranges[n-1][1] == r-1 {
			ranges[n-1][1] = r
		} else {
			ranges = append(ranges, [2]rune{r, r})
		}
	}
	fmt.Fprintf(&b, "/// The runes `unicode.IsLetter` accepts, as inclusive `(first, last)` ranges, sorted.\npub(crate) static LETTER: [(u32, u32); %d] = [", len(ranges))
	for i, p := range ranges {
		if i%8 == 0 {
			b.WriteString("\n    ")
		} else {
			b.WriteString(" ")
		}
		fmt.Fprintf(&b, "(0x%x, 0x%x),", p[0], p[1])
	}
	b.WriteString("\n];\n")
	return b.String()
}

