func stopWordTables() string {
	var b strings.Builder
	b.WriteString(header("Copyright (c) 2014 Couchbase, Inc.", "Apache-2.0",
		"github.com/blevesearch/bleve/v2 v2.5.7, analysis/lang/<lang>/stop_words_<lang>.go: the stop-word token maps\n"+
			" * Dgraph's tok/stopwords.go names, as bleve's registry loads them (the lists' own notices are in the Go files)"))
	cache := registry.NewCache()
	var names []string
	for _, lang := range stopLanguages {
		m, err := cache.TokenMapNamed("stop_" + lang)
		check(err)
		words := make([]string, 0, len(m))
		for w := range m {
			words = append(words, w)
		}
		sort.Strings(words)
		name := "STOP_" + strings.ToUpper(lang)
		names = append(names, name)
		fmt.Fprintf(&b, "/// bleve's `stop_%s`, sorted bytewise.\npub(crate) static %s: [&str; %d] = [", lang, name, len(words))
		for i, w := range words {
			if i%8 == 0 {
				b.WriteString("\n    ")
			} else {
				b.WriteString(" ")
			}
			b.WriteString(rustString(w))
			b.WriteString(",")
		}
		b.WriteString("\n];\n\n")
	}
	fmt.Fprintf(&b, "/// The stop words of each language of Dgraph's `langStops`, sorted by language.\npub(crate) static STOP_WORDS: [(&str, &[&str]); %d] = [\n", len(names))
	for i, lang := range stopLanguages {
		fmt.Fprintf(&b, "    (%q, &%s),\n", lang, names[i])
	}
	b.WriteString("];\n")
	return b.String()
}

// rustString quotes s as a Rust string literal.
func rustString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch {
		case r == '"' || r == '\\':
			b.WriteByte('\\')
			b.WriteRune(r)
		case r < 0x20 || r == 0x7f || !unicode.IsPrint(r):
			fmt.Fprintf(&b, "\\u{%x}", r)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}
