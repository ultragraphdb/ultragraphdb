// normTables writes the NFD properties the collation iterator reads (lead and trail combining class, number of
// leading non-starters) and the NFKD decompositions of the runes the collation tables mark as decomposing.
func normTables(coll *file) string {
	e := &emitter{}
	e.p("%s", header("2011", "unicode/norm, the NFD and NFKD Properties (Unicode "+norm.Version+")", false))
	e.str("The Unicode version of the normalization data.", "NORM_UNICODE_VERSION", norm.Version)

	type props struct{ lead, trail, nlead int }
	var ranges [][5]int // lo, hi, lead, trail, nlead
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if r >= 0xD800 && r <= 0xDFFF {
			continue
		}
		s := string(r)
		p := norm.NFD.PropertiesString(s)
		pr := props{int(p.LeadCCC()), int(p.TrailCCC()), nLeadingNonStarters(r)}
		if pr == (props{}) {
			continue
		}
		if n := len(ranges); n > 0 && ranges[n-1][1] == int(r)-1 && ranges[n-1][2] == pr.lead &&
			ranges[n-1][3] == pr.trail && ranges[n-1][4] == pr.nlead {
			ranges[n-1][1] = int(r)
			continue
		}
		ranges = append(ranges, [5]int{int(r), int(r), pr.lead, pr.trail, pr.nlead})
	}
	e.p("/// Runes with a non-zero NFD property, as `(first, last, lead_ccc, trail_ccc, leading_non_starters)`,\n")
	e.p("/// sorted. Every other rune has all three zero.\n")
	e.p("pub(crate) static NFD_PROPERTIES: [(u32, u32, u8, u8, u8); %d] = [\n", len(ranges))
	for i := 0; i < len(ranges); i += 3 {
		e.p("   ")
		for j := i; j < i+3 && j < len(ranges); j++ {
			x := ranges[j]
			e.p(" (0x%x, 0x%x, %d, %d, %d),", x[0], x[1], x[2], x[3], x[4])
		}
		e.p("\n")
	}
	e.p("];\n\n")

	// The runes any locale's table marks as decomposing.
	decomp := decomposingRunes(coll)
	var data []rune
	type entry struct {
		r          rune
		start, end int
	}
	var entries []entry
	for _, r := range decomp {
		d := norm.NFKD.PropertiesString(string(r)).Decomposition()
		if d == nil {
			check(fmt.Errorf("rune %U decomposes in the collation table but has no NFKD decomposition", r))
		}
		start := len(data)
		for _, c := range string(d) {
			data = append(data, c)
		}
		entries = append(entries, entry{r, start, len(data)})
	}
	e.p("/// The NFKD decompositions of the runes the collation tables decompose: `(rune, start, end)` into\n")
	e.p("/// `NFKD_DATA`, sorted by rune.\n")
	e.p("pub(crate) static NFKD_INDEX: [(u32, u16, u16); %d] = [\n", len(entries))
	for i := 0; i < len(entries); i += 4 {
		e.p("   ")
		for j := i; j < i+4 && j < len(entries); j++ {
			e.p(" (0x%x, %d, %d),", entries[j].r, entries[j].start, entries[j].end)
		}
		e.p("\n")
	}
	e.p("];\n\n")
	vals := make([]int64, len(data))
	for i, c := range data {
		vals[i] = int64(c)
	}
	e.intArray("The runes of the NFKD decompositions.", "NFKD_DATA", "u32", vals, 10, true)
	return e.b.String()
}

// nLeadingNonStarters returns the number of leading non-starters norm counts for r in NFD, derived through the
// public FirstBoundaryInString: after a rune with n leading non-starters, the stream-safe count overflows at the
// (31-n)th combining acute accent (one non-starter each).
func nLeadingNonStarters(r rune) int {
	s := string(r)
	if norm.NFD.FirstBoundaryInString(s) == 0 {
		return 0
	}
	const acute = "́"
	i := norm.NFD.FirstBoundaryInString(s + strings.Repeat(acute, 40))
	n := 30 - (i-len(s))/len(acute)
	if n <= 0 || n > 30 {
		check(fmt.Errorf("rune %U: cannot derive its leading non-starters (boundary at %d)", r, i))
	}
	return n
}

// decomposingRunes looks every rune up in every locale's collation trie and returns those whose element marks an
// NFKD decomposition (ceDecompose, at or above 0xF0000000), sorted.
func decomposingRunes(f *file) []rune {
	lookup := f.ints("mainLookup")
	values := f.ints("mainValues")
	var offsets [][2]int64
	for _, el := range expand(f, f.lit("locales")) {
		v := structFields(el, []string{"lookupOffset", "valuesOffset"})
		offsets = append(offsets, [2]int64{f.eval(v[0]).i, f.eval(v[1]).i})
	}
	const blockSize = 64
	seen := map[rune]bool{}
	var out []rune
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if r >= 0xD800 && r <= 0xDFFF {
			continue
		}
		var buf [4]byte
		n := utf8.EncodeRune(buf[:], r)
		b := buf[:n]
		for _, o := range offsets {
			index0 := lookup[blockSize*o[0]:]
			values0 := values[blockSize*o[1]:]
			var ce int64
			switch n {
			case 1:
				ce = values0[b[0]]
			case 2:
				i := index0[b[0]]
				ce = values[i<<6+int64(b[1])]
			case 3:
				i := index0[b[0]]
				i = lookup[i<<6+int64(b[1])]
				ce = values[i<<6+int64(b[2])]
			case 4:
				i := index0[b[0]]
				i = lookup[i<<6+int64(b[1])]
				i = lookup[i<<6+int64(b[2])]
				ce = values[i<<6+int64(b[3])]
			}
			if uint32(ce) >= 0xF0000000 && !seen[r] {
				seen[r] = true
				out = append(out, r)
			}
		}
	}
	return out
}

