func languageTables(f *file) string {
	e := &emitter{}
	e.p("%s", header("2013", "internal/language/tables.go", false))
	e.p("use crate::types::lang_tables::{FromTo, LikelyLangRegion, LikelyLangScript, LikelyScriptRegion, ")
	e.p("LikelyTag, ParentRel};\n\n")
	e.str("The CLDR version the language tables derive from.", "CLDR_VERSION", f.consts["CLDRVersion"].s)

	// Named identifiers: languages lower case, scripts title case, regions upper case.
	var names []string
	for n := range f.consts {
		if strings.HasPrefix(n, "_") {
			names = append(names, n)
		}
	}
	sort.Strings(names)
	e.p("\n// Named language, script and region identifiers.\n")
	for _, n := range names {
		id := n[1:]
		kind := "LANG"
		switch {
		case id == strings.ToUpper(id):
			kind = "REGION"
		case id[0] >= 'A' && id[0] <= 'Z':
			kind = "SCRIPT"
		}
		e.constant("", kind+"_"+strings.ToUpper(id), "u16", f.consts[n].i)
	}
	e.p("\n")
	e.constant("The language identifier of the non-canonical `und` entry.", "NON_CANONICAL_UND", "u16",
		f.consts["nonCanonicalUnd"].i)
	e.constant("The first private-use language identifier.", "LANG_PRIVATE_START", "u16",
		f.consts["langPrivateStart"].i)
	e.constant("The last private-use language identifier.", "LANG_PRIVATE_END", "u16", f.consts["langPrivateEnd"].i)
	e.constant("Identifiers from this offset on encode a three-letter code that has no index entry.",
		"LANG_NO_INDEX_OFFSET", "u16", f.consts["langNoIndexOffset"].i)
	e.constant("The offset of the ISO 3166-1 regions among the region identifiers.", "ISO_REGION_OFFSET", "u16",
		f.consts["isoRegionOffset"].i)
	e.constant("The number of region groups.", "N_REGION_GROUPS", "u8", f.consts["nRegionGroups"].i)
	e.p("\n")

	e.byteStr("Language index: four bytes per language, sorted.", "LANG", f.consts["lang"].s)
	e.intArray("Bit vector of the three-letter codes that are not used as an index.", "LANG_NO_INDEX", "u8",
		f.ints("langNoIndex"), 16, true)
	e.byteStr("Alternative ISO 639-3 codes.", "ALT_LANG_ISO3", f.consts["altLangISO3"].s)
	e.intArray("The languages of `ALT_LANG_ISO3`.", "ALT_LANG_INDEX", "u16", f.ints("altLangIndex"), 8, true)
	name2go["ALIAS_MAP"] = "AliasMap"
	e.structArray(f, "Language identifiers and their suggested replacements, sorted by `from`.", "ALIAS_MAP",
		"FromTo", []string{"From", "To"}, 4)
	e.intArray("The alias type of each `ALIAS_MAP` entry: 0 deprecated, 1 macro, 2 legacy.", "ALIAS_TYPES", "i8",
		f.ints("AliasTypes"), 16, false)
	e.byteStr("Script index: four bytes per script, sorted.", "SCRIPT", f.consts["script"].s)
	e.intArray("The suppress-script of each language.", "SUPPRESS_SCRIPT", "u8", f.ints("suppressScript"), 16,
		true)
	e.intArray("The type bits of each region.", "REGION_TYPES", "u8", f.ints("regionTypes"), 16, true)
	e.byteStr("Region index: four bytes per ISO region, sorted.", "REGION_ISO", f.consts["regionISO"].s)
	e.byteStr("Alternative ISO 3166-1 alpha-3 codes.", "ALT_REGION_ISO3", f.consts["altRegionISO3"].s)
	e.intArray("The regions of `ALT_REGION_ISO3`.", "ALT_REGION_IDS", "u16", f.ints("altRegionIDs"), 8, true)
	name2go["REGION_OLD_MAP"] = "regionOldMap"
	e.structArray(f, "Deprecated regions and their replacements, sorted by `from`.", "REGION_OLD_MAP", "FromTo",
		[]string{"From", "To"}, 4)
	e.intArray("The UN M.49 code of each region.", "M49", "i16", f.ints("m49"), 16, false)
	e.intArray("Indexes into `FROM_M49` by the three most significant bits of a code.", "M49_INDEX", "i16",
		f.ints("m49Index"), 9, false)
	e.intArray("UN M.49 codes (seven bits) and their regions (nine bits).", "FROM_M49", "u16", f.ints("fromM49"),
		12, true)

	// variantIndex: map[string]uint8, emitted sorted by key.
	lit := f.lit("variantIndex")
	type kv struct {
		k string
		v int64
	}
	var vs []kv
	for _, el := range lit.Elts {
		p := el.(*ast.KeyValueExpr)
		vs = append(vs, kv{f.eval(p.Key).s, f.eval(p.Value).i})
	}
	sort.Slice(vs, func(i, j int) bool { return vs[i].k < vs[j].k })
	e.p("/// The registered variants and their identifiers, sorted by name.\n")
	e.p("pub(crate) static VARIANT_INDEX: [(&str, u8); %d] = [\n", len(vs))
	for _, x := range vs {
		e.p("    (%s, 0x%x),\n", strconv.Quote(x.k), x.v)
	}
	e.p("];\n\n")

	name2go["LIKELY_SCRIPT"] = "likelyScript"
	e.structArray(f, "The most likely language and region of each script.", "LIKELY_SCRIPT", "LikelyLangRegion",
		[]string{"lang", "region"}, 4)
	name2go["LIKELY_LANG"] = "likelyLang"
	e.structArray(f, "The most likely script and region of each language.", "LIKELY_LANG", "LikelyScriptRegion",
		[]string{"region", "script", "flags"}, 3)
	name2go["LIKELY_LANG_LIST"] = "likelyLangList"
	e.structArray(f, "The lists of `LIKELY_LANG`.", "LIKELY_LANG_LIST", "LikelyScriptRegion",
		[]string{"region", "script", "flags"}, 3)
	name2go["LIKELY_REGION"] = "likelyRegion"
	e.structArray(f, "The most likely language and script of each region.", "LIKELY_REGION", "LikelyLangScript",
		[]string{"lang", "script", "flags"}, 3)
	name2go["LIKELY_REGION_LIST"] = "likelyRegionList"
	e.structArray(f, "The lists of `LIKELY_REGION`.", "LIKELY_REGION_LIST", "LikelyLangScript",
		[]string{"lang", "script", "flags"}, 3)
	name2go["LIKELY_REGION_GROUP"] = "likelyRegionGroup"
	e.structArray(f, "The most likely tag of each region group.", "LIKELY_REGION_GROUP", "LikelyTag",
		[]string{"lang", "region", "script"}, 3)
	e.intArray("The regions each region group contains, as a bit set.", "REGION_CONTAINMENT", "u64",
		f.ints("regionContainment"), 4, true)
	e.intArray("The inclusion index of each region.", "REGION_INCLUSION", "u8", f.ints("regionInclusion"), 16,
		true)
	e.intArray("The bit set of each inclusion index.", "REGION_INCLUSION_BITS", "u64",
		f.ints("regionInclusionBits"), 4, true)

	// parents: parentRel with a slice field.
	els := expand(f, f.lit("parents"))
	e.p("/// The CLDR parents of regional variants that are not the plain language.\n")
	e.p("pub(crate) static PARENTS: [ParentRel; %d] = [\n", len(els))
	for _, el := range els {
		vals := structFields(el, []string{"lang", "script", "maxScript", "toRegion", "fromRegion"})
		e.p("    ParentRel {\n")
		e.p("        lang: 0x%x,\n        script: 0x%x,\n        max_script: 0x%x,\n        to_region: 0x%x,\n",
			f.eval(vals[0]).i, f.eval(vals[1]).i, f.eval(vals[2]).i, f.eval(vals[3]).i)
		e.p("        from_region: &[")
		for k, r := range vals[4].(*ast.CompositeLit).Elts {
			if k > 0 {
				e.p(", ")
			}
			e.p("0x%x", f.eval(r).i)
		}
		e.p("],\n    },\n")
	}
	e.p("];\n")
	return e.b.String()
}

