// Rust emission

type emitter struct {
	b bytes.Buffer
}

func (e *emitter) p(format string, args ...any) {
	fmt.Fprintf(&e.b, format, args...)
}

// intArray writes `pub(crate) static NAME: [T; N] = [...]` with perLine values per line, in hex when hex is set.
func (e *emitter) intArray(doc, name, typ string, vals []int64, perLine int, hex bool) {
	e.p("/// %s\n", doc)
	e.p("pub(crate) static %s: [%s; %d] = [\n", name, typ, len(vals))
	for i := 0; i < len(vals); i += perLine {
		e.p("   ")
		for j := i; j < i+perLine && j < len(vals); j++ {
			if hex {
				e.p(" 0x%x,", vals[j])
			} else {
				e.p(" %d,", vals[j])
			}
		}
		e.p("\n")
	}
	e.p("];\n\n")
}

func (e *emitter) byteStr(doc, name, s string) {
	e.p("/// %s\n", doc)
	e.p("pub(crate) static %s: &[u8] = b\"", name)
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c == '"' || c == '\\':
			e.p("\\%c", c)
		case c >= 0x20 && c < 0x7f:
			e.p("%c", c)
		default:
			e.p("\\x%02x", c)
		}
		if i%96 == 95 && i+1 < len(s) {
			e.p("\\\n")
		}
	}
	e.p("\";\n\n")
}

func (e *emitter) str(doc, name, s string) {
	e.p("/// %s\n", doc)
	e.p("pub(crate) static %s: &str = %s;\n\n", name, strconv.Quote(s))
}

func (e *emitter) constant(doc, name, typ string, v int64) {
	if doc != "" {
		e.p("/// %s\n", doc)
	}
	e.p("pub(crate) const %s: %s = %d;\n", name, typ, v)
}

// structArray writes an array of a struct type whose fields are all integers.
func (e *emitter) structArray(f *file, doc, name, rustType string, fields []string, perLine int) {
	lit := f.lit(name2go[name])
	els := expand(f, lit)
	e.p("/// %s\n", doc)
	e.p("pub(crate) static %s: [%s; %d] = [\n", name, rustType, len(els))
	for i := 0; i < len(els); i += perLine {
		e.p("   ")
		for j := i; j < i+perLine && j < len(els); j++ {
			vals := structFields(els[j], fields)
			e.p(" %s {", rustType)
			for k, fl := range fields {
				v := int64(0)
				if vals[k] != nil {
					v = f.eval(vals[k]).i
				}
				if k > 0 {
					e.p(",")
				}
				e.p(" %s: 0x%x", snake(fl), v)
			}
			e.p(" },")
		}
		e.p("\n")
	}
	e.p("];\n\n")
}

// name2go maps a Rust table name to its Go variable.
var name2go = map[string]string{}

func snake(s string) string {
	var b strings.Builder
	for i, r := range s {
		if unicode.IsUpper(r) {
			if i > 0 {
				b.WriteByte('_')
			}
			b.WriteRune(unicode.ToLower(r))
		} else {
			b.WriteRune(r)
		}
	}
	return b.String()
}

