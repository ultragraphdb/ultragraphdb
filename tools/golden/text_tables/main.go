// unicode range tables

func unicodeTables() string {
	e := &emitter{}
	e.p("%s", header("2009", "unicode/tables.go (Unicode "+unicode.Version+")", true))
	e.str("The Unicode version of the range tables.", "UNICODE_TABLES_VERSION", unicode.Version)
	rangeTable(e, "Ideographic", "IDEOGRAPHIC", unicode.Ideographic)
	rangeTable(e, "Nd (decimal digits)", "ND", unicode.Nd)
	return e.b.String()
}

func rangeTable(e *emitter, doc, name string, t *unicode.RangeTable) {
	var rs [][3]uint32
	for _, r := range t.R16 {
		rs = append(rs, [3]uint32{uint32(r.Lo), uint32(r.Hi), uint32(r.Stride)})
	}
	for _, r := range t.R32 {
		rs = append(rs, [3]uint32{r.Lo, r.Hi, r.Stride})
	}
	e.p("/// The ranges of %s as `(lo, hi, stride)`, sorted.\n", doc)
	e.p("pub(crate) static %s: [(u32, u32, u32); %d] = [\n", name, len(rs))
	for i := 0; i < len(rs); i += 4 {
		e.p("   ")
		for j := i; j < i+4 && j < len(rs); j++ {
			e.p(" (0x%x, 0x%x, %d),", rs[j][0], rs[j][1], rs[j][2])
		}
		e.p("\n")
	}
	e.p("];\n")
}
