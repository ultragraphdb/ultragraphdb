func collateTables(f *file) string {
	e := &emitter{}
	e.p("%s", header("2012", "collate/tables.go", false))
	e.p("use crate::types::table_index::TableIndex;\n\n")
	e.str("The Unicode version the collation tables derive from.", "UNICODE_VERSION", f.consts["UnicodeVersion"].s)
	e.str("The CLDR version the collation tables derive from.", "CLDR_VERSION", f.consts["CLDRVersion"].s)
	e.str("The locales with a tailoring of their own, comma-separated; `und` first, the others sorted.",
		"AVAILABLE_LOCALES", f.strs["availableLocales"].s)
	e.constant("The largest primary weight that is variable.", "VAR_TOP", "u32", f.consts["varTop"].i)
	e.p("\n")
	name2go["LOCALES"] = "locales"
	e.structArray(f, "The offsets of each locale's tailoring in the main trie, in the order of `AVAILABLE_LOCALES`.",
		"LOCALES", "TableIndex", []string{"lookupOffset", "valuesOffset"}, 2)
	e.intArray("Expansion sequences: a length followed by that many collation elements.", "MAIN_EXPAND_ELEM",
		"u32", f.ints("mainExpandElem"), 8, true)
	e.intArray("Collation elements of contractions.", "MAIN_CONTRACT_ELEM", "u32", f.ints("mainContractElem"), 8,
		true)
	e.intArray("Trie values: the collation element of a rune, by block.", "MAIN_VALUES", "u32",
		f.ints("mainValues"), 8, true)
	e.intArray("Trie index: the block of the next UTF-8 byte.", "MAIN_LOOKUP", "u16", f.ints("mainLookup"), 12,
		true)
	// mainCTEntries: struct{ L, H, N, I uint8 }, positional.
	els := expand(f, f.lit("mainCTEntries"))
	e.p("/// The contraction tries: the states `{l, h, n, i}` of each trie.\n")
	e.p("pub(crate) static MAIN_CT_ENTRIES: [[u8; 4]; %d] = [\n", len(els))
	for i := 0; i < len(els); i += 6 {
		e.p("   ")
		for j := i; j < i+6 && j < len(els); j++ {
			vals := structFields(els[j], []string{"L", "H", "N", "I"})
			e.p(" [")
			for k, v := range vals {
				if k > 0 {
					e.p(", ")
				}
				e.p("0x%x", f.eval(v).i)
			}
			e.p("],")
		}
		e.p("\n")
	}
	e.p("];\n")
	return e.b.String()
}

