// Go source evaluation

// file holds the evaluated top-level declarations of one Go file.
type file struct {
	consts map[string]value
	vars   map[string]*ast.CompositeLit
	types  map[string]ast.Expr
	strs   map[string]value // string-valued vars and consts
}

// value is an evaluated constant expression: an integer or a string.
type value struct {
	isStr bool
	i     int64
	s     string
}

func parseFile(path string) *file {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, path, nil, 0)
	check(err)
	res := &file{consts: map[string]value{}, vars: map[string]*ast.CompositeLit{}, types: map[string]ast.Expr{},
		strs: map[string]value{}}
	for _, d := range f.Decls {
		g, ok := d.(*ast.GenDecl)
		if !ok {
			continue
		}
		for _, sp := range g.Specs {
			switch s := sp.(type) {
			case *ast.TypeSpec:
				res.types[s.Name.Name] = s.Type
			case *ast.ValueSpec:
				for i, n := range s.Names {
					if i >= len(s.Values) {
						continue
					}
					switch v := s.Values[i].(type) {
					case *ast.CompositeLit:
						res.vars[n.Name] = v
					default:
						val := res.eval(v)
						if g.Tok == token.CONST {
							res.consts[n.Name] = val
						}
						if val.isStr {
							res.strs[n.Name] = val
						}
					}
				}
			}
		}
	}
	return res
}

func (f *file) eval(e ast.Expr) value {
	switch x := e.(type) {
	case *ast.BasicLit:
		switch x.Kind {
		case token.INT:
			n, err := strconv.ParseInt(x.Value, 0, 64)
			if err != nil {
				u, err2 := strconv.ParseUint(x.Value, 0, 64)
				check(err2)
				n = int64(u)
			}
			return value{i: n}
		case token.STRING:
			s, err := strconv.Unquote(x.Value)
			check(err)
			return value{isStr: true, s: s}
		}
	case *ast.BinaryExpr:
		a, b := f.eval(x.X), f.eval(x.Y)
		if x.Op == token.ADD && a.isStr && b.isStr {
			return value{isStr: true, s: a.s + b.s}
		}
		if x.Op == token.ADD {
			return value{i: a.i + b.i}
		}
	case *ast.UnaryExpr:
		if x.Op == token.SUB {
			return value{i: -f.eval(x.X).i}
		}
	case *ast.ParenExpr:
		return f.eval(x.X)
	case *ast.Ident:
		if v, ok := f.consts[x.Name]; ok {
			return v
		}
	case *ast.CallExpr:
		// Conversions such as tag.Index("...") or ID(3).
		if len(x.Args) == 1 {
			return f.eval(x.Args[0])
		}
	}
	check(fmt.Errorf("cannot evaluate %T %v", e, e))
	return value{}
}

// elems evaluates an array or slice literal of integers, expanding keyed elements and the array length.
func (f *file) ints(name string) []int64 {
	lit := f.lit(name)
	var out []int64
	for _, el := range expand(f, lit) {
		if el == nil {
			out = append(out, 0)
			continue
		}
		out = append(out, f.eval(el).i)
	}
	return out
}

func (f *file) lit(name string) *ast.CompositeLit {
	lit, ok := f.vars[name]
	if !ok {
		check(fmt.Errorf("no composite literal %s", name))
	}
	return lit
}

// expand returns the elements of an array or slice literal by index; nil marks a zero element.
func expand(f *file, lit *ast.CompositeLit) []ast.Expr {
	var out []ast.Expr
	idx := 0
	for _, el := range lit.Elts {
		if kv, ok := el.(*ast.KeyValueExpr); ok {
			idx = int(f.eval(kv.Key).i)
			el = kv.Value
		}
		for len(out) <= idx {
			out = append(out, nil)
		}
		out[idx] = el
		idx++
	}
	if at, ok := lit.Type.(*ast.ArrayType); ok && at.Len != nil {
		if _, ell := at.Len.(*ast.Ellipsis); !ell {
			n := int(f.eval(at.Len).i)
			for len(out) < n {
				out = append(out, nil)
			}
			if len(out) != n {
				check(fmt.Errorf("literal has %d elements, type says %d", len(out), n))
			}
		}
	}
	return out
}

// structFields returns the field values of a struct literal in the order of fields; missing fields are nil.
func structFields(el ast.Expr, fields []string) []ast.Expr {
	out := make([]ast.Expr, len(fields))
	if el == nil {
		return out
	}
	lit := el.(*ast.CompositeLit)
	for i, e := range lit.Elts {
		if kv, ok := e.(*ast.KeyValueExpr); ok {
			name := kv.Key.(*ast.Ident).Name
			pos := -1
			for j, fl := range fields {
				if fl == name {
					pos = j
				}
			}
			if pos < 0 {
				check(fmt.Errorf("unknown field %s", name))
			}
			out[pos] = kv.Value
		} else {
			out[i] = e
		}
	}
	return out
}

